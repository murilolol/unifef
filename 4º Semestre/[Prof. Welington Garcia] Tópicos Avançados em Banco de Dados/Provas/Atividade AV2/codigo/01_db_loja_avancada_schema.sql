BEGIN;

DROP TABLE IF EXISTS auditoria_produtos, auditoria_precos, historico_estoque,
 notificacoes, historico_status_pedidos, comissoes, movimentacoes_financeiras,
 avaliacoes, pagamentos, itens_pedido, pedidos, produtos, categorias,
 fornecedores, clientes, funcionarios CASCADE;

CREATE TABLE clientes (
 id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE,
 telefone VARCHAR(20),
 cidade VARCHAR(80) NOT NULL,
 uf CHAR(2) NOT NULL,
 limite_credito NUMERIC(12,2) NOT NULL DEFAULT 1000 CHECK (limite_credito >= 0),
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 data_cadastro DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE funcionarios (
 id_funcionario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 cargo VARCHAR(60) NOT NULL,
 salario NUMERIC(12,2) NOT NULL CHECK (salario > 0),
 percentual_comissao NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (percentual_comissao BETWEEN 0 AND 100),
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 data_admissao DATE NOT NULL
);

CREATE TABLE fornecedores (
 id_fornecedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 razao_social VARCHAR(130) NOT NULL,
 cnpj CHAR(14) NOT NULL UNIQUE,
 email VARCHAR(150),
 ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE categorias (
 id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(80) NOT NULL UNIQUE,
 percentual_desconto NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (percentual_desconto BETWEEN 0 AND 100)
);

CREATE TABLE produtos (
 id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(130) NOT NULL,
 id_categoria INTEGER NOT NULL REFERENCES categorias(id_categoria),
 id_fornecedor INTEGER NOT NULL REFERENCES fornecedores(id_fornecedor),
 preco NUMERIC(12,2) NOT NULL CHECK (preco > 0),
 custo NUMERIC(12,2) NOT NULL CHECK (custo >= 0),
 estoque INTEGER NOT NULL DEFAULT 0 CHECK (estoque >= 0),
 estoque_minimo INTEGER NOT NULL DEFAULT 5 CHECK (estoque_minimo >= 0),
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 data_cadastro DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE pedidos (
 id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cliente INTEGER NOT NULL REFERENCES clientes(id_cliente),
 id_funcionario INTEGER REFERENCES funcionarios(id_funcionario),
 data_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status VARCHAR(20) NOT NULL DEFAULT 'ABERTO' CHECK (status IN ('ABERTO','PAGO','CANCELADO','ENTREGUE')),
 desconto NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (desconto >= 0),
 frete NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (frete >= 0),
 observacao TEXT
);

CREATE TABLE itens_pedido (
 id_item INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_pedido INTEGER NOT NULL REFERENCES pedidos(id_pedido) ON DELETE CASCADE,
 id_produto INTEGER NOT NULL REFERENCES produtos(id_produto),
 quantidade INTEGER NOT NULL CHECK (quantidade > 0),
 preco_unitario NUMERIC(12,2) NOT NULL CHECK (preco_unitario > 0),
 UNIQUE (id_pedido,id_produto)
);

CREATE TABLE pagamentos (
 id_pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_pedido INTEGER NOT NULL REFERENCES pedidos(id_pedido),
 valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
 forma VARCHAR(20) NOT NULL CHECK (forma IN ('PIX','CARTAO','BOLETO','DINHEIRO')),
 data_pagamento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE','CONFIRMADO','ESTORNADO'))
);

CREATE TABLE avaliacoes (
 id_avaliacao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cliente INTEGER NOT NULL REFERENCES clientes(id_cliente),
 id_produto INTEGER NOT NULL REFERENCES produtos(id_produto),
 nota INTEGER NOT NULL CHECK (nota BETWEEN 1 AND 5),
 comentario TEXT,
 data_avaliacao DATE NOT NULL DEFAULT CURRENT_DATE,
 UNIQUE (id_cliente,id_produto)
);

-- Tabelas auxiliares para auditoria, historico e integracoes
CREATE TABLE historico_estoque (
 id_historico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_produto INTEGER NOT NULL REFERENCES produtos(id_produto),
 tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('ENTRADA','SAIDA','AJUSTE')),
 quantidade INTEGER NOT NULL CHECK (quantidade > 0),
 estoque_anterior INTEGER NOT NULL,
 estoque_atual INTEGER NOT NULL,
 motivo VARCHAR(200) NOT NULL,
 data_movimentacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE auditoria_precos (
 id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_produto INTEGER NOT NULL REFERENCES produtos(id_produto),
 preco_anterior NUMERIC(12,2) NOT NULL,
 preco_novo NUMERIC(12,2) NOT NULL,
 data_alteracao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 usuario_bd TEXT NOT NULL DEFAULT CURRENT_USER
);

CREATE TABLE auditoria_produtos (
 id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_produto INTEGER NOT NULL,
 nome_produto VARCHAR(130) NOT NULL,
 preco NUMERIC(12,2) NOT NULL,
 estoque INTEGER NOT NULL,
 operacao VARCHAR(10) NOT NULL,
 data_operacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE historico_status_pedidos (
 id_historico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_pedido INTEGER NOT NULL REFERENCES pedidos(id_pedido),
 status_anterior VARCHAR(20) NOT NULL,
 status_novo VARCHAR(20) NOT NULL,
 data_alteracao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE comissoes (
 id_comissao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_pedido INTEGER NOT NULL UNIQUE REFERENCES pedidos(id_pedido),
 id_funcionario INTEGER NOT NULL REFERENCES funcionarios(id_funcionario),
 valor NUMERIC(12,2) NOT NULL CHECK (valor >= 0),
 data_calculo TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notificacoes (
 id_notificacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tipo VARCHAR(40) NOT NULL,
 mensagem TEXT NOT NULL,
 id_produto INTEGER REFERENCES produtos(id_produto),
 data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 lida BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE movimentacoes_financeiras (
 id_movimentacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_pagamento INTEGER NOT NULL REFERENCES pagamentos(id_pagamento),
 tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('RECEITA','ESTORNO')),
 valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
 data_movimentacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (id_pagamento,tipo)
);

