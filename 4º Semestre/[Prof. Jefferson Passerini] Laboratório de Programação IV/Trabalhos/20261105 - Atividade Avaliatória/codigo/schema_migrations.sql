-- Exercício 2: Changeset 03 - Criação da tabela de Cursos
-- --------------------------------------------------------------------
-- changeset murilodev:03-criar-tabela-curso
CREATE TABLE IF NOT EXISTS curso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    carga_horaria INTEGER NOT NULL,
    nivel VARCHAR(20) NOT NULL,
    instrutor_id BIGINT NOT NULL,
    CONSTRAINT chk_curso_carga_horaria CHECK (carga_horaria >= 1 AND carga_horaria <= 400),
    CONSTRAINT chk_curso_nivel CHECK (nivel IN ('INICIANTE', 'INTERMEDIARIO', 'AVANCADO'))
);
-- rollback DROP TABLE IF EXISTS curso CASCADE;

-- --------------------------------------------------------------------
-- Exercício 2: Changeset 04 - Adição da Chave Estrangeira (FK)
-- --------------------------------------------------------------------
-- changeset murilodev:04-adicionar-fk-curso-instrutor
ALTER TABLE curso
    ADD CONSTRAINT fk_curso_instrutor
    FOREIGN KEY (instrutor_id)
    REFERENCES instrutor (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE;
-- rollback ALTER TABLE curso DROP CONSTRAINT IF EXISTS fk_curso_instrutor;

