-- --------------------------------------------------------------------
-- Consultas de verificação da integridade referencial
-- --------------------------------------------------------------------
-- 1. Listagem dos cursos com seus respectivos instrutores (JOIN)
SELECT 
    c.id AS curso_id,
    c.titulo AS curso_titulo,
    c.carga_horaria,
    c.nivel,
    i.id AS instrutor_id,
    i.nome AS instrutor_nome,
    i.email AS instrutor_email
FROM curso c
INNER JOIN instrutor i ON c.instrutor_id = i.id
ORDER BY c.titulo ASC;

